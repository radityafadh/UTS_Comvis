def hitung_mse_psnr(asli, hasil):
    asli = np.asarray(asli, dtype=np.uint8)
    hasil = np.asarray(hasil)

    if hasil.ndim == 3:
        hasil = cv2.cvtColor(hasil, cv2.COLOR_BGR2GRAY)

    if hasil.shape != asli.shape:
        hasil = cv2.resize(
            hasil.astype(np.uint8),
            (asli.shape[1], asli.shape[0]),
            interpolation=cv2.INTER_NEAREST
        )
    else:
        hasil = hasil.astype(np.uint8)

    mse = float(mean_squared_error(asli, hasil))
    psnr = (
        float("inf") if mse == 0
        else float(peak_signal_noise_ratio(
            asli, hasil, data_range=255
        ))
    )
    return mse, psnr


