# 1. RUMUS MSE DAN PSNR
def hitung_mse_psnr(img_asli, img_hasil):
    """
    MSE  = rata-rata kuadrat selisih piksel.
    PSNR = 10 * log10(255^2 / MSE).
    """
    a = np.asarray(img_asli, dtype=np.uint8)
    b = np.asarray(img_hasil)

    if b.ndim == 3:
        b = cv2.cvtColor(b, cv2.COLOR_BGR2GRAY)

    if b.shape != a.shape:
        b = cv2.resize(
            b.astype(np.uint8),
            (a.shape[1], a.shape[0]),
            interpolation=cv2.INTER_NEAREST
        )
    else:
        b = b.astype(np.uint8)

    mse = float(mean_squared_error(a, b))

    psnr = (
        float("inf")
        if mse == 0
        else float(peak_signal_noise_ratio(a, b, data_range=255))
    )

    return mse, psnr


# 2. EVALUASI GAMBAR ASLI VS MASK OTSU DAN GABOR
def evaluasi_mse_psnr(img_asli, mask_otsu, peta_gabor):
    # Pastikan citra asli grayscale uint8
    img_asli = np.asarray(img_asli, dtype=np.uint8)

    # Mask Otsu menjadi citra 8-bit
    mask_otsu = np.asarray(mask_otsu)
    if mask_otsu.max() <= 1:
        mask_otsu = mask_otsu * 255
    mask_otsu = mask_otsu.astype(np.uint8)

    # Normalisasi respons Gabor ke rentang 0–255
    gabor_8bit = cv2.normalize(
        np.asarray(peta_gabor, dtype=np.float32),
        None, 0, 255, cv2.NORM_MINMAX
    ).astype(np.uint8)

    mse_otsu, psnr_otsu = hitung_mse_psnr(
        img_asli, mask_otsu
    )

    mse_gabor, psnr_gabor = hitung_mse_psnr(
        img_asli, gabor_8bit
    )

    return {
        "MSE_Otsu": mse_otsu,
        "PSNR_Otsu_dB": psnr_otsu,
        "MSE_Gabor": mse_gabor,
        "PSNR_Gabor_dB": psnr_gabor
    }


